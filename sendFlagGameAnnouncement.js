import { default as makeWASocket, useMultiFileAuthState, fetchLatestBaileysVersion, DisconnectReason } from "@whiskeysockets/baileys";
import qrcode from "qrcode-terminal";
import { connectDB } from "./database/db.js";
import { KINGDOMS } from "./config.js";

async function sendFlagGameAnnouncement() {
  try {
    // الاتصال بقاعدة البيانات
    await connectDB();
    console.log("✅ تم الاتصال بقاعدة البيانات");

    // الاتصال بـ WhatsApp
    const { state, saveCreds } = await useMultiFileAuthState("./auth");
    const { version } = await fetchLatestBaileysVersion();
    
    const sock = makeWASocket({
      version,
      auth: state
    });

    sock.ev.on("connection.update", async (update) => {
      const { qr, connection, lastDisconnect } = update;

      if (qr) {
        console.log("\n📱 امسح QR من واتساب:\n");
        qrcode.generate(qr, { small: true });
      }

      if (connection === "open") {
        console.log("✅ متصل بـ WhatsApp");

        // الحصول على معرّف المجموعة الأساسية
        const mainGroupJid = KINGDOMS.clover.mainGroup;

        // الرسالة الجميلة
        const message = `╔════════════════════════════════════╗
║  🎉 لعبة جديدة وممتعة جداً 🚩        ║
╚════════════════════════════════════╝

*السلام عليكم ورحمة الله وبركاته* 👋

يسعدنا إعلانكم عن **لعبة الأعلام الجديدة** 🌍

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🚩 *ما هي لعبة الأعلام؟*
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

لعبة تفاعلية وممتعة تختبر معرفتك بأعلام دول العالم!

✨ *الآلية:*
   • يتم عرض صورة علم دولة معينة
   • لديك 10 ثواني فقط للإجابة ⏱️
   • تلميح بعد 2 ثانية (أول + آخر حرف) 💡
   • اجب بشكل صحيح واكسب نقطتين 💰

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🎮 *أنماط اللعبة:*
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

*1️⃣ النمط الجماعي 👥*
   جميع أعضاء المجموعة يشاركون
   أول من يجيب بشكل صحيح يفوز 🏆

*2️⃣ النمط الثنائي ⚔️*
   منافسة مباشرة بين شخصين
   الأسرع والأذكى يفوز! 

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

📊 *الإحصائيات:*
   • 213 دول من دول العالم 🌎
   • صور أعلام حقيقية وعالية الجودة
   • نقاط تُحفظ في ملفك الشخصي

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🚀 *كيف تبدأ اللعبة؟*
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

قم بهذه الخطوات البسيطة:

*الطريقة الأولى:*
  /اعلام

*الطريقة الثانية:*
  /ألعاب
  ثم اختر رقم 6️⃣

*الطريقة الثالثة:*
  /أوامر
  وابحث عن لعبة الأعلام

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

💡 *نصائح للفوز:*
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

👀 انتبه لألوان وتصميم العلم
⚡ كن سريعاً - الوقت محدود!
🎯 استخدم التلميح بذكاء
📝 تأكد من كتابة الاسم الصحيح

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🎁 *للمشرفين والأدمن* 🔰
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

فقط المشرفون والأدمن يستطيعون بدء اللعبة
اكتب /اعلام أو /ألعاب لبدء لعبة جديدة

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

🏆 *الميزات:*
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

✅ لعبة سريعة وممتعة جداً
✅ منافسة عادلة وشفافة
✅ نقاط حقيقية تُحفظ
✅ لا توجد رسوم أو متطلبات خاصة
✅ يمكنك اللعب في أي وقت

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

📢 *ماذا تنتظر!* 🎉
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

ابدأ اللعبة الآن واستمتع مع أصدقائك! 🚀

اكتب: /اعلام أو /ألعاب (اختر 6️⃣)

━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━

*حظاً موفقاً للجميع!* ✨
تمتعوا باللعبة الجديدة! 🎮

╔════════════════════════════════════╗
║     والسلام عليكم ورحمة الله     ║
╚════════════════════════════════════╝`;

        // إرسال الرسالة
        try {
          await sock.sendMessage(mainGroupJid, { text: message });
          console.log("✅ تم إرسال الرسالة بنجاح إلى المجموعة الأساسية!");
          
          // إغلاق الاتصال بعد الإرسال
          setTimeout(() => {
            process.exit(0);
          }, 1000);
        } catch (sendError) {
          console.error("❌ خطأ في إرسال الرسالة:", sendError.message);
          process.exit(1);
        }
      }

      if (connection === "close") {
        if (lastDisconnect?.error?.output?.statusCode !== DisconnectReason.loggedOut) {
          console.log("❌ تم قطع الاتصال، إعادة المحاولة...");
          process.exit(1);
        }
      }
    });

    sock.ev.on("creds.update", saveCreds);
  } catch (error) {
    console.error("❌ خطأ:", error.message);
    process.exit(1);
  }
}

// تشغيل السكربت
sendFlagGameAnnouncement();
