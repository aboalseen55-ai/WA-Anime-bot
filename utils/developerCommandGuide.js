function buildDeveloperCommandGuide() {
  let message = `🛠️ *دليل أوامر المطور*\n`;
  message += `مرتب حسب الفئة مع شرح مختصر لكل أمر.\n`;
  message += `━━━━━━━━━━━━━━━━━━━━\n`;

  for (const group of COMMAND_GROUPS) {
    message += `\n*${group.title}*\n`;
    for (const [command, description] of group.commands) {
      message += `• ${command}\n  ${description}\n`;
    }
  }

  return message.trim();
}

function splitMessage(text, maxLength = 3200) {
  const chunks = [];
  let current = "";

  for (const section of text.split(/\n(?=\*)/)) {
    if ((current + "\n" + section).length > maxLength && current) {
      chunks.push(current.trim());
      current = section;
    } else {
      current = current ? `${current}\n${section}` : section;
    }
  }

  if (current.trim()) chunks.push(current.trim());
  return chunks;
}

export async function handleDeveloperCommandGuide(sock, jid, sender, trimmedText) {
  const command = String(trimmedText || "").split(/\s+/)[0].toLowerCase();
  if (!DEVELOPER_GUIDE_COMMANDS.has(command)) return false;

  if (!isDeveloper(sender)) {
    await sock.sendMessage(jid, { text: "❌ هذا الأمر خاص بالمطور فقط." });
    return true;
  }

  const chunks = splitMessage(buildDeveloperCommandGuide());
  for (let index = 0; index < chunks.length; index++) {
    const suffix = chunks.length > 1 ? `\n\n(${index + 1}/${chunks.length})` : "";
    await sock.sendMessage(jid, { text: `${chunks[index]}${suffix}` });
  }

  return true;
}
