// دالة لإرسال القوانين
export async function sendRulesMessage(sock, jid) {
  try {
    // تقسيم الرسالة إلى أجزاء إذا كانت طويلة جداً
    if (RULES_TEXT.length > 4096) {
      const chunks = [];
      let currentChunk = '';

      for (const line of RULES_TEXT.split('\n')) {
        if ((currentChunk + line + '\n').length > 4000) {
          chunks.push(currentChunk);
          currentChunk = line + '\n';
        } else {
          currentChunk += line + '\n';
        }
      }

      if (currentChunk.trim()) {
        chunks.push(currentChunk);
      }

      // إرسال الأجزاء بالترتيب
      for (const chunk of chunks) {
        await sock.sendMessage(jid, { text: chunk });
        // إضافة تأخير بسيط بين الأجزاء
        await new Promise(resolve => setTimeout(resolve, 500));
      }
    } else {
      await sock.sendMessage(jid, { text: RULES_TEXT });
    }

    console.log(`✅ تم إرسال القوانين للمجموعة`);
  } catch (error) {
    console.error('❌ خطأ في إرسال القوانين:', error);
  }
}

// نظام التذكيرات الدورية
const reminderIntervals = new Map();

export function startReminderSystem(sock, jid, intervalHours = 12) {
  // إذا كان هناك تذكير قديم، قم بوقفه
  if (reminderIntervals.has(jid)) {
    clearInterval(reminderIntervals.get(jid));
  }

  // إنشاء تذكير جديد
  const intervalId = setInterval(async () => {
    await sendReminderMessage(sock, jid);
  }, intervalHours * 60 * 60 * 1000); // تحويل الساعات إلى ملي ثانية

  reminderIntervals.set(jid, intervalId);
  console.log(`✅ تم تفعيل نظام التذكيرات الدورية للمجموعة (كل ${intervalHours} ساعة)`);
}

export function stopReminderSystem(jid) {
  if (reminderIntervals.has(jid)) {
    clearInterval(reminderIntervals.get(jid));
    reminderIntervals.delete(jid);
    console.log(`✅ تم إيقاف نظام التذكيرات للمجموعة`);
  }
}

export function getReminderSystemStatus() {
  return {
    activeCounts: reminderIntervals.size,
    groups: Array.from(reminderIntervals.keys())
  };
}
