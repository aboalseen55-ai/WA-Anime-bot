// دالة للحصول على أعلى رتبة للعضو بناءً على نجوم الرتبة (النظام الجديد: جميع الرتب تلقائية)
export function getHighestRank(kingdom, rankStars) {
  const kingdomRanksData = kingdomRanks[kingdom] || kingdomRanks.clover;
  let highestRank = null;
  let maxStars = -1;

  for (const [key, rankData] of Object.entries(kingdomRanksData)) {
    // جميع الرتب تلقائية الآن
    if (rankStars >= rankData.requiredStars && rankData.requiredStars > maxStars) {
      highestRank = key;
      maxStars = rankData.requiredStars;
    }
  }

  return highestRank;
}

// دالة للحصول على معلومات الرتبة
export function getRankInfo(kingdom, rankKey) {
  const kingdomRanksData = kingdomRanks[kingdom] || kingdomRanks.clover;
  return kingdomRanksData[rankKey] || null;
}

// دالة لعرض الرتبة بصيغة جميلة
export function displayRank(kingdom, rankKey) {
  if (!rankKey) return '';
  const rank = getRankInfo(kingdom, rankKey);
  return rank ? `${rank.emoji} ${rank.name}` : '';
}

// دالة مساعدة لتحديث رتبة المستخدم تلقائياً بناءً على نجومه
export function updateUserRank(user, kingdom) {
  if (!user) return { changed: false, oldRank: null, newRank: null };

  const rankStars = user.rankStarsByKingdom?.[kingdom] || 0;
  const newRank = getHighestRank(kingdom, rankStars);
  const oldRank = user.kingdomRankByKingdom?.[kingdom];

  if (oldRank !== newRank) {
    if (!user.kingdomRankByKingdom) user.kingdomRankByKingdom = {};
    user.kingdomRankByKingdom[kingdom] = newRank;
    if (typeof user.markModified === 'function') {
      user.markModified('kingdomRankByKingdom');
    }
    return { changed: true, oldRank, newRank };
  }

  return { changed: false, oldRank, newRank };
}

// دالة لعرض جميع الرتب (النظام الجديد: رتب المملكة العليا والإدارية)
export function getAllRanksDisplay(kingdom = 'clover') {
  const kingdomRanksData = kingdomRanks[kingdom] || kingdomRanks.clover;
  let display = `*┇🩸𝘏.𝘜.𝘕 𝘒𝘐𝘕𝘎𝘋𝘖𝘔𝘌🎖️夜┇*\n`;
  display += `*❃━━━━═⏣⊰🍀⊱⏣═━━━━━❃*\n`;
  display += `*~رتب المملكة العليا ↶⛓️~*\n`;
  display += `*❃━━━━═⏣⊰🍀⊱⏣═━━━━━❃*\n\n`;

  // رتب المملكة العليا
  const supremeRanks = ['emperor', 'emperorVice', 'lord', 'lordVice', 'marquis', 'marquisVice'];
  for (const rankKey of supremeRanks) {
    const rankData = kingdomRanksData[rankKey];
    if (rankData) {
      display += `*₪┇↲${rankData.name}┇${rankData.emoji}┇⇜ ⇘*\n`;
      display += `*قرار رتب عليا*\n\n`;
    }
  }

  display += `*❃━━━━═⏣⊰🩸⊱⏣═━━━━━❃*\n`;
  display += `*~الرتب الادارية العلية ↶┇~*\n`;
  display += `*❃━━━━═⏣⊰🩸⊱⏣═━━━━━❃*\n\n`;

  // الرتب الإدارية العليا
  const highAdminRanks = ['king', 'kingVice', 'duke', 'dukeVice'];
  for (const rankKey of highAdminRanks) {
    const rankData = kingdomRanksData[rankKey];
    if (rankData) {
      display += `*⌬┇↲${rankData.name}┇${rankData.emoji}┇⇜⇘*\n`;
      display += `${rankData.requiredStars}\n\n`;
    }
  }

  display += `*🩸⊱⏣═━━━━━❃*\n`;
  display += `*~رتب الادارية الخاصة بالنقابه↶┇~*\n`;
  display += `*❃━━━━═⏣⊰🩸⊱⏣═━━━━━❃*\n\n`;

  // رتب النقابة الإدارية
  const guildRanks = ['admiral', 'admiralVice', 'dean', 'hashira', 'eliteKing', 'supremeLord', 'flagBearer', 'standardBearer', 'traineeSupervisor'];
  for (const rankKey of guildRanks) {
    const rankData = kingdomRanksData[rankKey];
    if (rankData) {
      display += `*⌬┇↲${rankData.name}|${rankData.requiredStars}|┇${rankData.emoji}┇⇜⇘*\n`;
    }
  }

  display += `\n*❃━━━━═⏣⊰*\n`;

  return display;
}

