// معالجة اختيار القائمة
export async function handleCommandsChoice(sock, jid, sender, text) {
    const kingdom = getKingdomIdFromGroupJid(jid);
    const userIsAdmin = await isAdmin(sender, kingdom);
    const userIsModerator = await isModerator(sender, kingdom);
    const choice = text.trim();

    if (choice === '1') {
        await showMemberCommands(sock, jid);
    } else if (choice === '2') {
        await showGamesCommands(sock, jid);
    } else if (choice === '3') {
        await showBankCommands(sock, jid);
    } else if (choice === '4') {
        if (!userIsModerator) {
            await sock.sendMessage(jid, { text: '❌ هذه الأوامر متاحة للمشرفين والأدمنين الأساسيين فقط!\n\nليس لديك صلاحية لعرض هذه القائمة.' });
            return;
        }
        await showModeratorCommands(sock, jid);
    } else if (choice === '5') {
        if (!userIsAdmin) {
            await sock.sendMessage(jid, { text: '❌ هذه الأوامر متاحة للأدمن الرئيسي فقط!\n\nليس لديك صلاحية لعرض هذه القائمة.' });
            return;
        }
        await showAdminCommands(sock, jid);
    } else if (choice === '6') {
        if (!userIsAdmin) {
            await sock.sendMessage(jid, { text: '❌ هذه الأوامر متاحة للأدمن الرئيسي فقط!\n\nليس لديك صلاحية لعرض هذه القائمة.' });
            return;
        }
        await showRanksSystem(sock, jid);
    } else if (choice === '7') {
        await showSearchCommands(sock, jid);
    } else {
        await sock.sendMessage(jid, { text: '❌ اختيار غير صحيح!\n\nاكتب أحد الأرقام المتاحة في القائمة' });
    }
}
